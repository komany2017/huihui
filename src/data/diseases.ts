export function getDiseaseById(id: string): Disease | undefined {
  return DISEASES.find((d) => d.id === id)
}

export function searchDiseases(keyword: string, category?: string): Disease[] {
  return DISEASES.filter((d) => {
    if (category && category !== 'all' && d.category !== category) return false
    if (keyword) {
      const k = keyword.trim()
      if (k && !d.name.includes(k) && !(d.alias || '').includes(k) && !d.symptoms.some((s) => s.includes(k))) {
        return false
      }
    }
    return true
  })
}

